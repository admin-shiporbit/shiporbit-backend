SET ROUNDING = 'EXACT', UPDATED_AT = CURRENT_TIMESTAMP
FROM SO_RATE_SERVICE s
WHERE c.SERVICE_ID = s.ID
  AND s.PRICING_MODEL = 'B2B_FREIGHT'
  AND c.VERSION_LABEL = 'SAMPLE-2026-10';

