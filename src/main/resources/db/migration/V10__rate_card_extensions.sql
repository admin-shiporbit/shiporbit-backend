-- V10: Rate-card extensions + SAMPLE rows that exercise them.
-- (V9 is reserved for payment-gateway's wallet migration.)
-- All new columns are nullable or defaulted: existing V8 data and the
-- golden quotes (201301 -> 560001, COD, GENERAL, parcel, pickup 2026-10-12)
-- are unchanged.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Schema
-- ---------------------------------------------------------------------

-- Slab variants. NULL = applies to any value.
-- Lookup: among rows whose range contains the chargeable unit, prefer an
-- exact PAYMENT_MODE / SHIPMENT_TYPE match, else the NULL row.
ALTER TABLE SO_RATE_SLAB
    ADD COLUMN PAYMENT_MODE  VARCHAR(10),            -- COD / PREPAID
    ADD COLUMN SHIPMENT_TYPE VARCHAR(10),            -- DOCUMENT / PARCEL
    ADD CONSTRAINT SO_CK_RATE_SLAB_PAYMENT_MODE CHECK (PAYMENT_MODE IN ('COD', 'PREPAID')),
    ADD CONSTRAINT SO_CK_RATE_SLAB_SHIPMENT_TYPE CHECK (SHIPMENT_TYPE IN ('DOCUMENT', 'PARCEL'));

ALTER TABLE SO_RATE_SLAB DROP CONSTRAINT SO_UQ_RATE_SLAB;
CREATE UNIQUE INDEX SO_UX_RATE_SLAB ON SO_RATE_SLAB
    (RATE_CARD_ID, DIRECTION, LOCATION_KEY, COALESCE(PAYMENT_MODE, 'ANY'), COALESCE(SHIPMENT_TYPE, 'ANY'), FROM_UNIT);

-- Additional-unit rounding.
--   CEIL_STEP: CEIL((x - FIRST_UNIT) / ADD_UNIT) * ADD_RATE   (V6 behaviour)
--   EXACT    :      (x - FIRST_UNIT) / ADD_UNIT  * ADD_RATE
ALTER TABLE SO_RATE_CARD
    ADD COLUMN ROUNDING VARCHAR(10) NOT NULL DEFAULT 'CEIL_STEP',
    ADD CONSTRAINT SO_CK_RATE_CARD_ROUNDING CHECK (ROUNDING IN ('CEIL_STEP', 'EXACT'));

-- Charge rules:
--   VALID_FROM / VALID_TO : rule applies only when pickup date is inside (NULL = open).
--   APPLIES_VALUE         : value for APPLIES_WHEN = 'CATEGORY' (product category).
--   BASE CHARGEABLE_WEIGHT: tier (TIER_FROM/TIER_TO) is checked against chargeable weight.
ALTER TABLE SO_RATE_CHARGE_RULE
    ADD COLUMN VALID_FROM    DATE,
    ADD COLUMN VALID_TO      DATE,
    ADD COLUMN APPLIES_VALUE VARCHAR(50),
    ADD CONSTRAINT SO_CK_RATE_RULE_VALIDITY CHECK (VALID_FROM IS NULL OR VALID_TO IS NULL OR VALID_TO >= VALID_FROM);

ALTER TABLE SO_RATE_CHARGE_RULE DROP CONSTRAINT SO_CK_RATE_RULE_BASE;
ALTER TABLE SO_RATE_CHARGE_RULE
    ADD CONSTRAINT SO_CK_RATE_RULE_BASE CHECK (BASE IN ('BASE_FREIGHT', 'CHARGE_CODES', 'COD_AMOUNT', 'DECLARED_VALUE',
                                                        'CHARGEABLE_WEIGHT', 'NONE'));

ALTER TABLE SO_RATE_CHARGE_RULE DROP CONSTRAINT SO_CK_RATE_RULE_APPLIES;
ALTER TABLE SO_RATE_CHARGE_RULE
    ADD CONSTRAINT SO_CK_RATE_RULE_APPLIES CHECK (APPLIES_WHEN IN ('ALWAYS', 'COD', 'PREPAID', 'ODA_DESTINATION', 'ODA_PICKUP',
                                                               'SPECIAL_CITY', 'RISK_OWNER', 'RISK_CARRIER',
                                                               'ADDON_OTP', 'ADDON_QC', 'ADDON_FRAGILE', 'CATEGORY')),
    ADD CONSTRAINT SO_CK_RATE_RULE_APPLIES_VALUE CHECK (APPLIES_WHEN <> 'CATEGORY' OR APPLIES_VALUE IS NOT NULL);

