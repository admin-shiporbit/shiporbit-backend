-- =====================================================================
-- V6: Generic rate-card storage for all delivery partners.
-- One set of tables for every partner and pricing model; partners differ
-- only in data. Read by the rate calculator, written by rate-card import.
-- =====================================================================

-- Service offered by a partner (e.g. DELHIVERY / SURFACE_05KG).
CREATE TABLE SO_RATE_SERVICE
(
    ID            BIGSERIAL PRIMARY KEY,
    PARTNER_ID    INT          NOT NULL,
    SERVICE_CODE  VARCHAR(50)  NOT NULL,
    SERVICE_NAME  VARCHAR(100) NOT NULL,
    PRICING_MODEL VARCHAR(20)  NOT NULL,
    MODE          VARCHAR(20)  NOT NULL,
    ENABLED       BOOLEAN      NOT NULL DEFAULT TRUE,
    CREATED_AT    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT SO_FK_RATE_SERVICE_PARTNER FOREIGN KEY (PARTNER_ID) REFERENCES SO_DELIVERY_PARTNER_LIST (ID),
    CONSTRAINT SO_UQ_RATE_SERVICE UNIQUE (PARTNER_ID, SERVICE_CODE),
    CONSTRAINT SO_CK_RATE_SERVICE_MODEL CHECK (PRICING_MODEL IN ('ZONE_SLAB', 'DISTANCE_BAND', 'B2B_FREIGHT', 'HYPERLOCAL')),
    CONSTRAINT SO_CK_RATE_SERVICE_MODE CHECK (MODE IN ('SURFACE', 'AIR', 'SURFACE_AIR', 'HYPERLOCAL'))
);

-- Versioned rate card of a service. Only one ACTIVE card per service.
CREATE TABLE SO_RATE_CARD
(
    ID                       BIGSERIAL PRIMARY KEY,
    SERVICE_ID               BIGINT        NOT NULL,
    VERSION_LABEL            VARCHAR(40)   NOT NULL,
    STATUS                   VARCHAR(10)   NOT NULL,          -- DRAFT / ACTIVE / RETIRED
    DATA_STATUS              VARCHAR(10)   NOT NULL,          -- SAMPLE / CONTRACT
    EFFECTIVE_FROM           DATE          NOT NULL,
    EFFECTIVE_TO             DATE,                            -- NULL = open-ended
    VOLUMETRIC_DIVISOR       NUMERIC(10, 2),                  -- cm3 per kg; NULL = dead weight only
    CFT_KG                   NUMERIC(10, 2),                  -- B2B: kg per cubic foot; NULL otherwise
    MIN_CHARGEABLE_WEIGHT_KG NUMERIC(10, 3) NOT NULL DEFAULT 0,
    MAX_WEIGHT_KG            NUMERIC(10, 3) NOT NULL,
    MAX_DISTANCE_KM          NUMERIC(10, 2),                  -- HYPERLOCAL only
    MPS_RULE                 VARCHAR(10)   NOT NULL DEFAULT 'TOTAL',             -- TOTAL / PER_PIECE
    RTO_RULE                 VARCHAR(25)   NOT NULL DEFAULT 'PERCENT_OF_FORWARD', -- PERCENT_OF_FORWARD / NOT_APPLICABLE
    RTO_PERCENT              NUMERIC(6, 2),                   -- 100 = same as forward
    MIN_BILL                 NUMERIC(10, 2) NOT NULL DEFAULT 0,
    RATES_INCLUDE_GST        BOOLEAN       NOT NULL DEFAULT FALSE,
    CREATED_AT               TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT               TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT SO_FK_RATE_CARD_SERVICE FOREIGN KEY (SERVICE_ID) REFERENCES SO_RATE_SERVICE (ID),
    CONSTRAINT SO_UQ_RATE_CARD_VERSION UNIQUE (SERVICE_ID, VERSION_LABEL),
    CONSTRAINT SO_CK_RATE_CARD_STATUS CHECK (STATUS IN ('DRAFT', 'ACTIVE', 'RETIRED')),
    CONSTRAINT SO_CK_RATE_CARD_DATA_STATUS CHECK (DATA_STATUS IN ('SAMPLE', 'CONTRACT')),
    CONSTRAINT SO_CK_RATE_CARD_MPS CHECK (MPS_RULE IN ('TOTAL', 'PER_PIECE')),
    CONSTRAINT SO_CK_RATE_CARD_RTO CHECK (RTO_RULE IN ('PERCENT_OF_FORWARD', 'NOT_APPLICABLE')),
    CONSTRAINT SO_CK_RATE_CARD_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM)
);
CREATE UNIQUE INDEX SO_UX_RATE_CARD_ONE_ACTIVE ON SO_RATE_CARD (SERVICE_ID) WHERE STATUS = 'ACTIVE';

-- Base freight.
-- LOCATION_KEY: zone (ZONE_SLAB), distance band (DISTANCE_BAND),
--               zone pair e.g. 'N1-S1' (B2B_FREIGHT), vehicle e.g. 'BIKE' (HYPERLOCAL).
-- A row applies when FROM_UNIT < chargeable <= TO_UNIT (TO_UNIT NULL = no upper limit).
-- Freight = FIRST_RATE + CEIL((chargeable - FIRST_UNIT) / ADD_UNIT) * ADD_RATE
--           (no additional part when chargeable <= FIRST_UNIT or ADD_UNIT = 0).
CREATE TABLE SO_RATE_SLAB
(
    ID           BIGSERIAL PRIMARY KEY,
    RATE_CARD_ID BIGINT         NOT NULL,
    DIRECTION    VARCHAR(10)    NOT NULL,                     -- FORWARD / REVERSE
    LOCATION_KEY VARCHAR(20)    NOT NULL,
    UNIT         VARCHAR(5)     NOT NULL,                     -- KG / KM
    FROM_UNIT    NUMERIC(10, 3) NOT NULL,
    TO_UNIT      NUMERIC(10, 3),
    FIRST_UNIT   NUMERIC(10, 3) NOT NULL,
    FIRST_RATE   NUMERIC(10, 2) NOT NULL,
    ADD_UNIT     NUMERIC(10, 3) NOT NULL,
    ADD_RATE     NUMERIC(10, 2) NOT NULL,
    CONSTRAINT SO_FK_RATE_SLAB_CARD FOREIGN KEY (RATE_CARD_ID) REFERENCES SO_RATE_CARD (ID),
    CONSTRAINT SO_UQ_RATE_SLAB UNIQUE (RATE_CARD_ID, DIRECTION, LOCATION_KEY, FROM_UNIT),
    CONSTRAINT SO_CK_RATE_SLAB_DIRECTION CHECK (DIRECTION IN ('FORWARD', 'REVERSE')),
    CONSTRAINT SO_CK_RATE_SLAB_UNIT CHECK (UNIT IN ('KG', 'KM')),
    CONSTRAINT SO_CK_RATE_SLAB_RANGE CHECK (TO_UNIT IS NULL OR TO_UNIT > FROM_UNIT),
    CONSTRAINT SO_CK_RATE_SLAB_VALUES CHECK (FIRST_UNIT >= 0 AND FIRST_RATE >= 0 AND ADD_UNIT >= 0 AND ADD_RATE >= 0)
);
CREATE INDEX SO_IDX_RATE_SLAB_LOOKUP ON SO_RATE_SLAB (RATE_CARD_ID, DIRECTION, LOCATION_KEY);

-- Every charge beyond base freight. A charge the partner does not levy is
-- stored with RATE_VALUE/FIXED_AMOUNT = 0 so "not levied" is explicit.
-- Amount:
--   FLAT     -> FIXED_AMOUNT
--   PERCENT  -> FIXED_AMOUNT + RATE_VALUE% * base
--   PER_UNIT -> RATE_VALUE * chargeable weight (or km)
-- then clamped to MIN_AMOUNT / MAX_AMOUNT, rounded to 2 decimals.
-- BASE: BASE_FREIGHT, CHARGE_CODES (sum of BASE_CODES lines so far),
--       COD_AMOUNT, DECLARED_VALUE, NONE.
-- Rules are applied in SEQ order. TIER_FROM/TIER_TO restrict a rule to a range of its base
-- (e.g. a COD fee that is flat below Rs 2,000 and a percentage above).
CREATE TABLE SO_RATE_CHARGE_RULE
(
    ID           BIGSERIAL PRIMARY KEY,
    RATE_CARD_ID BIGINT         NOT NULL,
    CHARGE_CODE  VARCHAR(30)    NOT NULL,
    SEQ          INT            NOT NULL,
    CALC_TYPE    VARCHAR(10)    NOT NULL,
    RATE_VALUE   NUMERIC(12, 4) NOT NULL DEFAULT 0,
    FIXED_AMOUNT NUMERIC(10, 2) NOT NULL DEFAULT 0,
    MIN_AMOUNT   NUMERIC(10, 2),
    MAX_AMOUNT   NUMERIC(10, 2),
    BASE         VARCHAR(20)    NOT NULL,
    BASE_CODES   VARCHAR(200),
    TIER_FROM    NUMERIC(12, 2),
    TIER_TO      NUMERIC(12, 2),
    APPLIES_WHEN VARCHAR(20)    NOT NULL,
    DIRECTIONS   VARCHAR(30)    NOT NULL DEFAULT 'FORWARD,RTO,REVERSE',
    CONSTRAINT SO_FK_RATE_RULE_CARD FOREIGN KEY (RATE_CARD_ID) REFERENCES SO_RATE_CARD (ID),
    CONSTRAINT SO_UQ_RATE_RULE UNIQUE (RATE_CARD_ID, CHARGE_CODE, SEQ),
    CONSTRAINT SO_CK_RATE_RULE_CALC CHECK (CALC_TYPE IN ('FLAT', 'PERCENT', 'PER_UNIT')),
    CONSTRAINT SO_CK_RATE_RULE_BASE CHECK (BASE IN ('BASE_FREIGHT', 'CHARGE_CODES', 'COD_AMOUNT', 'DECLARED_VALUE', 'NONE')),
    CONSTRAINT SO_CK_RATE_RULE_BASE_CODES CHECK (BASE <> 'CHARGE_CODES' OR BASE_CODES IS NOT NULL),
    CONSTRAINT SO_CK_RATE_RULE_APPLIES CHECK (APPLIES_WHEN IN ('ALWAYS', 'COD', 'PREPAID', 'ODA_DESTINATION', 'ODA_PICKUP',
                                                            'SPECIAL_CITY', 'RISK_OWNER', 'RISK_CARRIER',
                                                            'ADDON_OTP', 'ADDON_QC', 'ADDON_FRAGILE'))
);
CREATE INDEX SO_IDX_RATE_RULE_CARD ON SO_RATE_CHARGE_RULE (RATE_CARD_ID, SEQ);

-- Origin/destination pincode -> zone, distance band or B2B zone pair, per partner and pricing model.
-- Not used for HYPERLOCAL (same-city check uses SO_PARTNER_PINCODE.CITY_CODE).
CREATE TABLE SO_ZONE_MAP
(
    PARTNER_ID          INT         NOT NULL,
    PRICING_MODEL       VARCHAR(20) NOT NULL,
    ORIGIN_PINCODE      VARCHAR(6)  NOT NULL,
    DESTINATION_PINCODE VARCHAR(6)  NOT NULL,
    LOCATION_KEY        VARCHAR(20) NOT NULL,
    CONSTRAINT SO_PK_ZONE_MAP PRIMARY KEY (PARTNER_ID, PRICING_MODEL, ORIGIN_PINCODE, DESTINATION_PINCODE),
    CONSTRAINT SO_FK_ZONE_MAP_PARTNER FOREIGN KEY (PARTNER_ID) REFERENCES SO_DELIVERY_PARTNER_LIST (ID),
    CONSTRAINT SO_CK_ZONE_MAP_MODEL CHECK (PRICING_MODEL IN ('ZONE_SLAB', 'DISTANCE_BAND', 'B2B_FREIGHT'))
);

-- Serviceability and surcharge flags per partner and pincode.
CREATE TABLE SO_PARTNER_PINCODE
(
    PARTNER_ID     INT         NOT NULL,
    PINCODE        VARCHAR(6)  NOT NULL,
    CITY_CODE      VARCHAR(30) NOT NULL,
    STATE_ID       INT         NOT NULL,
    PICKUP         BOOLEAN     NOT NULL,
    DELIVERY       BOOLEAN     NOT NULL,
    COD            BOOLEAN     NOT NULL,
    PREPAID        BOOLEAN     NOT NULL,
    REVERSE_PICKUP BOOLEAN     NOT NULL,
    ODA            BOOLEAN     NOT NULL,
    SPECIAL_CITY   BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT SO_PK_PARTNER_PINCODE PRIMARY KEY (PARTNER_ID, PINCODE),
    CONSTRAINT SO_FK_PARTNER_PINCODE_PARTNER FOREIGN KEY (PARTNER_ID) REFERENCES SO_DELIVERY_PARTNER_LIST (ID),
    CONSTRAINT SO_FK_PARTNER_PINCODE_STATE FOREIGN KEY (STATE_ID) REFERENCES SO_STATES (STATE_ID)
);
CREATE INDEX SO_IDX_PARTNER_PINCODE_PIN ON SO_PARTNER_PINCODE (PINCODE);
